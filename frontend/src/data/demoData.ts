// Generate hourly traffic data for charts
export function generateHourlyData(date?: Date): TrafficDataPoint[] {
  const hours = Array.from({ length: 24 }, (_, i) => i);
  const baseVolumes = [200, 150, 100, 80, 120, 450, 1200, 2100, 2400, 1800, 1400, 1600, 1800, 1500, 1300, 1600, 2000, 2200, 1800, 1400, 1000, 700, 450, 300];
  const baseSpeeds = [55, 60, 62, 65, 58, 40, 22, 14, 12, 18, 24, 22, 20, 24, 26, 22, 16, 14, 18, 24, 32, 40, 48, 55];
  
  return hours.map((h) => ({
    time: `${h.toString().padStart(2, '0')}:00`,
    vehicleCount: baseVolumes[h] + Math.floor(Math.random() * 100 - 50),
    averageSpeed: Math.max(8, baseSpeeds[h] + Math.floor(Math.random() * 6 - 3)),
    queueLength: Math.max(0, Math.floor((2400 - baseVolumes[h]) / 2 + Math.random() * 50)),
    congestionLevel: baseVolumes[h] > 2000 ? 'severe' : baseVolumes[h] > 1500 ? 'high' : baseVolumes[h] > 800 ? 'moderate' : 'low',
  }));
}

export function generateWeeklyData() {
  const days = ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun'];
  const multipliers = [1.0, 1.0, 1.05, 1.0, 1.1, 0.75, 0.5];
  return days.map((day, i) => ({
    day,
    avgCongestion: Math.floor(65 * multipliers[i] + Math.random() * 10),
    peakVolume: Math.floor(2200 * multipliers[i] + Math.random() * 100),
    avgDelay: Math.floor(18 * multipliers[i] + Math.random() * 4),
  }));
}

